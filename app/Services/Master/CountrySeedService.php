    /**
     * Upsert semua data negara referensi ke tabel countries, dikunci oleh iso_code.
     *
     * @return array{created: int, updated: int}
     */
    public function seed(): array
    {
        $created = 0;
        $updated = 0;

        foreach ($this->countries() as $row) {
            $country = Country::query()->updateOrCreate(
                ['iso_code' => $row['iso_code']],
                ['name' => $row['name'], 'iso_code3' => $row['iso_code3'], 'phone_code' => $row['phone_code']],
            );

            $country->wasRecentlyCreated ? $created++ : $updated++;
        }

        return ['created' => $created, 'updated' => $updated];
    }
